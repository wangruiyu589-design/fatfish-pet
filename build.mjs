/**
 * Builds the shipped client bundle by inlining the whale-maid sprite sheet,
 * face avatar and the generated UI CSS into the plain-JS Client module.
 *
 *   node build.mjs
 *
 * Runtime assets are only embedded here; `art/whale/source/` is not needed by
 * the Client at runtime.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const templatePath = join(here, 'src', 'client.template.js')
const uiCssPath = join(here, 'src', 'ui.css')
const sheetPath = join(here, 'art', 'whale', 'sprite-sheet.webp')
const avatarPath = join(here, 'art', 'whale', 'avatar.webp')
const liveBundlePath = join(here, 'live2d-bundle.js')
const outPath = join(here, 'client.js')

const [template, uiCss, sheet, avatar, liveBundle] = await Promise.all([
  readFile(templatePath, 'utf8'),
  readFile(uiCssPath, 'utf8'),
  readFile(sheetPath),
  readFile(avatarPath),
  readFile(liveBundlePath, 'utf8'),
])

for (const marker of ['__FFISH_UI_CSS__', '__BUILD_TIME__']) {
  if (!template.includes(marker)) {
    throw new Error(`client template is missing marker ${marker}`)
  }
  if (template.split(marker).length !== 2) {
    throw new Error(`client template must contain marker ${marker} exactly once`)
  }
}

const sheetUrl = `data:image/webp;base64,${sheet.toString('base64')}`
const avatarUrl = `data:image/webp;base64,${avatar.toString('base64')}`
const assetCss = [
  '/* Inlined runtime artwork (generated by build.mjs). */',
  '.ffish-sprite { background-image: url("' + sheetUrl + '"); }',
  '.ffish-avatar-face { background-image: url("' + avatarUrl + '"); }',
].join('\n')

const sanitize = (value) => value.replaceAll('</script', '<\\/script')
const built = liveBundle + '\n;try{window.FatFishLive2D=FatFishLive2D}catch(error){}\n'
  + ";try{fetch('/fatfish-pet/client-state',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({live:'script-loaded'})}).catch(function(){})}catch(error){}\n"
  + template
  .replaceAll('__FFISH_UI_CSS__', JSON.stringify(sanitize(uiCss + '\n' + assetCss)))
  .replaceAll('__BUILD_TIME__', JSON.stringify(new Date().toISOString()))

await writeFile(outPath, built, 'utf8')
console.log(`wrote ${outPath} (${Buffer.byteLength(built)} bytes); sheet=${sheet.length}B avatar=${avatar.length}B`)
